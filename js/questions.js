  // 카테고리별로 질문 하나씩 랜덤 추출
  getDailyQuestions() {
    const result = [];
    const order = ['economy', 'relation', 'health', 'growth', 'parenting', 'etc'];
    order.forEach(catId => {
      const pool = this.pool[catId];
      if (!pool?.length) return;
      const picked = pool[Math.floor(Math.random() * pool.length)];
      const cat = this.categories.find(c => c.id === catId);
      result.push({ ...picked, catId, catLabel: cat.label, catColor: cat.color, catBg: cat.bg });
    });
    return result;
  },

  getCategoryInfo(catId) {
    return this.categories.find(c => c.id === catId) || this.categories[5];
  },
